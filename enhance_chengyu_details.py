def generate_enhanced_files():
    """글자별 풀이와 유의어 상세 정보 추가"""
    output_dir = Path(r"D:\_Git\ChinWord\Doc\Markdown\hsk-themes\Idioms")

    # i01_Top.md 생성 (1-100번)
    with open(output_dir / "i01_Top.md", 'w', encoding='utf-8') as f:
        f.write("# 4자성어 (四字成語) - 1~100\n\n")
        f.write("> 순위: 1-100번\n")
        f.write("> 수준: 광범위 학습 (200개 중)\n")
        f.write("> 성어 수: 100개\n\n")
        f.write("---\n\n")

        # 1-10번: 상세 데이터
        for rank in range(1, 11):
            if rank in chengyu_details:
                detail = chengyu_details[rank]
                f.write(f"### {rank}. {detail['name']} / [성어]\n\n")
                f.write(f"- 글자별 풀이:\n")
                for hanzi, pinyin, radical, meaning in detail['chars']:
                    f.write(f"  - {hanzi} ({pinyin}): {radical} — {meaning}\n")
                f.write(f"- 유의어:\n")
                for hanzi, pinyin, meaning in detail['synonyms']:
                    f.write(f"  - {hanzi} ({pinyin}): {meaning}\n")
                f.write(f"\n---\n\n")

        # 11-100번: 기본 데이터
        for rank in range(11, 101):
            if rank in basic_chengyu:
                hanzi, desc, chars, syns = basic_chengyu[rank]
                f.write(f"### {rank}. {hanzi} / [성어]\n\n")
                f.write(f"- 글자별 풀이:\n")
                for char_data in chars:
                    if len(char_data) == 3:
                        char, pinyin, radical = char_data
                        f.write(f"  - {char} ({pinyin}): {radical}\n")
                f.write(f"- 유의어:\n")
                for syn_data in syns:
                    if len(syn_data) == 3:
                        hanzi, pinyin, meaning = syn_data
                        f.write(f"  - {hanzi} ({pinyin}): {meaning}\n")
                f.write(f"\n---\n\n")

    print("i01_Top.md (1-100번) 상세 정보 추가 완료")
    print("i02_Top.md는 구조 재정렬 예정")

generate_enhanced_files()
