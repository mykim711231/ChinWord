def generate_final_split_files():
    """최종 200개 성어를 4개 파일로 분리하여 생성"""
    output_dir = Path(r"D:\_Git\ChinWord\Doc\Markdown\hsk-themes\Idioms")
    output_dir.mkdir(parents=True, exist_ok=True)

    # 4개 파일 생성
    file_configs = [
        (1, 50, 'i01_Top.md', '1'),
        (51, 100, 'i02_Top.md', '2'),
        (101, 150, 'i03_Top.md', '3'),
        (151, 200, 'i04_Top.md', '4'),
    ]

    for start, end, filename, part_num in file_configs:
        data_slice = [item for item in all_chengyu if start <= item[0] <= end]

        md_content = f"# 4자성어 (四字成語) - 파트 {part_num}\n\n"
        md_content += f"> 순위: {start}번-{end}번\n"
        md_content += f"> 수준: 광범위 학습 (200개 중)\n"
        md_content += f"> 성어 수: {len(data_slice)}개\n\n"
        md_content += "---\n\n"

        for rank, hanzi, pinyin, meaning_ko, source, etymology in data_slice:
            md_content += f"### {rank}. {hanzi} / {pinyin} / [성어] / {meaning_ko}\n\n"
            md_content += f"- 원문: {hanzi} ({pinyin}) — {source}\n"
            md_content += f"- 유래: {etymology}\n"
            md_content += f"- 글자별 풀이: [상세 정보는 개선 중]\n"
            md_content += f"- 유의어: [상세 정보는 개선 중]\n"
            md_content += f"\n---\n\n"

        with open(output_dir / filename, 'w', encoding='utf-8') as f:
            f.write(md_content)

        print(f"- {filename} ({start}-{end}): {len(data_slice)}개 성어 생성 완료")

    print(f"\n전체 {len(all_chengyu)}개 성어 완성")
    print(f"파일 위치: Doc/Markdown/hsk-themes/Idioms/")

generate_final_split_files()
