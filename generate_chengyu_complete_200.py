def generate_complete_split_files(all_data):
    """4개 파일로 나누어 생성"""
    output_dir = Path(r"D:\_Git\ChinWord\Doc\Markdown\hsk-themes\Idioms")
    output_dir.mkdir(parents=True, exist_ok=True)

    # 4개 파일 생성: i01(1-50), i02(51-100), i03(101-150), i04(151-200)
    file_ranges = [(1, 50, 'i01_Top.md'), (51, 100, 'i02_Top.md'), (101, 150, 'i03_Top.md'), (151, 200, 'i04_Top.md')]

    for start, end, filename in file_ranges:
        md_content = f"# 4자성어 (四字成語) - 파트 {filename.split('_')[0]}\n\n"
        md_content += f"> 순위: {start}번-{end}번\n"
        md_content += f"> 수준: 광범위 학습\n"
        md_content += f"> 성어 수: {min(end, len(all_data)) - start + 1}개\n\n"
        md_content += "---\n\n"

        for rank, hanzi, pinyin, meaning_ko, source, etymology in all_data[start-1:min(end, len(all_data))]:
            md_content += f"### {rank}. {hanzi} / {pinyin} / [성어] / {meaning_ko}\n\n"
            md_content += f"- 원문: {hanzi} ({pinyin}) — {source}\n"
            md_content += f"- 유래: {etymology}\n"
            md_content += f"- 글자별 풀이: [상세 정보는 추가 예정]\n"
            md_content += f"- 유의어: [상세 정보는 추가 예정]\n"
            md_content += f"\n---\n\n"

        with open(output_dir / filename, 'w', encoding='utf-8') as f:
            f.write(md_content)

        print(f"생성 완료: {filename} ({start}-{min(end, len(all_data))}번)")

